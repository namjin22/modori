import { describe, expect, it } from "vitest";

import { dragRange } from "@/lib/event-drag";

describe("dragRange", () => {
  it("하루짜리 일정은 끄는 쪽으로 늘어난다", () => {
    expect(dragRange("2026-09-28", "2026-09-28", "2026-09-28", "2026-09-30")).toEqual({ start: "2026-09-28", end: "2026-09-30" });
    expect(dragRange("2026-09-28", "2026-09-28", "2026-09-28", "2026-09-25")).toEqual({ start: "2026-09-25", end: "2026-09-28" });
  });

  it("마지막 날을 잡으면 종료일을 옮겨 늘이거나 줄인다", () => {
    expect(dragRange("2026-09-28", "2026-10-02", "2026-10-02", "2026-09-29")).toEqual({ start: "2026-09-28", end: "2026-09-29" });
    expect(dragRange("2026-09-28", "2026-09-30", "2026-09-30", "2026-10-01")).toEqual({ start: "2026-09-28", end: "2026-10-01" });
  });

  it("첫날을 잡으면 시작일을 옮긴다(줄이기도 된다)", () => {
    expect(dragRange("2026-09-28", "2026-09-30", "2026-09-28", "2026-09-29")).toEqual({ start: "2026-09-29", end: "2026-09-30" });
    expect(dragRange("2026-09-28", "2026-09-30", "2026-09-28", "2026-09-25")).toEqual({ start: "2026-09-25", end: "2026-09-30" });
  });

  it("반대편 끝을 넘어가면 두 끝이 바뀐다", () => {
    expect(dragRange("2026-09-28", "2026-09-30", "2026-09-28", "2026-10-02")).toEqual({ start: "2026-09-30", end: "2026-10-02" });
  });

  it("가운데를 잡으면 길이 그대로 기간째 옮긴다", () => {
    expect(dragRange("2026-09-28", "2026-09-30", "2026-09-29", "2026-10-01")).toEqual({ start: "2026-09-30", end: "2026-10-02" });
  });
});
